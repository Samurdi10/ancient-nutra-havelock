-- Product price reference, pulled from the Ancient Nutra Shopify storefront
-- (ancientnutra.com/products.json) for reporting purposes only — e.g.
-- showing current selling price alongside sales in the product breakdown.
-- Matched against bill line items by exact product name; not every POS
-- product name matches the website's title exactly (naming varies), so some
-- products in reports may show no price — that's expected, not a bug.
--
-- Re-run this migration (or a refreshed version of it) periodically to keep
-- prices current; there's no live sync to the storefront.

create table public.havelock_product_prices (
  product_name text primary key,
  price numeric not null,
  compare_at_price numeric,
  updated_at timestamptz not null default now()
);

alter table public.havelock_product_prices enable row level security;

create policy "Authenticated staff can read product prices"
  on public.havelock_product_prices for select
  to authenticated
  using (true);

grant select on public.havelock_product_prices to authenticated;

